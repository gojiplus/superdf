test_that("simulated collection reaches inference without exposing potential outcomes", {
  skip_if_not_installed("survey")
  skip_if_not_installed("estimatr")
  skip_if_not_installed("arrow")
  skip_if_not_installed("zip")
  source(
    system.file("examples", "simulated_study.R", package = "superdf"),
    local = TRUE
  )
  population <- simulate_population()
  study <- collect_study(population)
  expect_equal(nrow(study), 96L)
  expect_equal(length(unique(study$school)), 24L)
  units <- unique(as.data.frame(study)[c("school", "district", "offer")])
  expect_equal(as.vector(table(units$district, units$offer)), rep(6L, 4))
  expect_false(any(c("y0", "y1") %in% names(collection_data(study))))
  positions <- match(study$id, population$id)
  expect_equal(study$baseline, population$baseline[positions])
  expect_equal(study$followup, population$y0[positions] + 2 * study$offer)
  path <- tempfile(fileext = ".superdf")
  on.exit(unlink(path), add = TRUE)
  write_superdf(study, path)
  received <- read_superdf(path)
  result <- analyze_study(received)
  expect_equal(result$table, analyze_study(study)$table)
  expect_equal(result$baseline$analysis$design_df, 22L)
  expect_equal(result$effect$analysis$target, "randomized roster")
  expect_true(all(is.finite(as.matrix(result$table[-1]))))
})
